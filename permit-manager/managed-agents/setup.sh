#!/usr/bin/env bash
# One-time setup: create the environment, the three specialist agents, the
# coordinator (with the specialists as its roster), and the email-style memory
# store. Writes the resulting IDs to .ids.env for run_session.py.
#
# Prereqs:
#   - ant CLI installed + authenticated (`ant auth login`) on a workspace with
#     Managed Agents access. See shared docs: https://platform.claude.com/docs/en/api/sdks/cli
#   - Run from this directory:  ./setup.sh
set -euo pipefail
cd "$(dirname "$0")"

echo "Creating environment..."
ENV_ID=$(ant beta:environments create < permit-desk.environment.yaml --transform id -r)

echo "Creating specialist agents..."
PAPERWORK_ID=$(ant beta:agents create < paperwork.agent.yaml --transform id -r)
RESEARCH_ID=$(ant beta:agents create < research.agent.yaml   --transform id -r)
VOICE_ID=$(ant beta:agents create < voice.agent.yaml         --transform id -r)

echo "Creating coordinator (roster: $PAPERWORK_ID, $RESEARCH_ID, $VOICE_ID)..."
COORD_ID=$(ant beta:agents create --transform id -r <<YAML
name: Permit Desk
model: claude-opus-4-8
system: |
$(sed 's/^/  /' permit-desk.system.md)
tools:
  - type: agent_toolset_20260401
multiagent:
  type: coordinator
  agents:
    - $PAPERWORK_ID
    - $RESEARCH_ID
    - $VOICE_ID
YAML
)

echo "Creating email-style memory store..."
STYLE_STORE_ID=$(ant beta:memory-stores create \
  --name "email-style-guide" \
  --description "The user's email voice/style, learned once and reused for every draft." \
  --transform id -r)

cat > .ids.env <<EOF
# Generated by setup.sh - do not edit by hand.
ENV_ID=$ENV_ID
COORD_ID=$COORD_ID
STYLE_STORE_ID=$STYLE_STORE_ID
PAPERWORK_ID=$PAPERWORK_ID
RESEARCH_ID=$RESEARCH_ID
VOICE_ID=$VOICE_ID
EOF

echo
echo "Done. IDs written to .ids.env:"
cat .ids.env
echo
echo "Next: export GITHUB_TOKEN=<fine-grained PAT, Contents:Read on g0ddley/g0ddley-s-games>"
echo "Then: python run_session.py \"Start the permit package for <project>...\""
