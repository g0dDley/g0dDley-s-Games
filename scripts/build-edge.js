// Packs the client into an asset bundle + generates the Supabase Edge Function.
// The function source stays tiny; the (large) asset bundle is uploaded separately:
//   node scripts/build-edge.js
//   <deploy supabase/functions/game via MCP/CLI>
//   curl -X POST -H "x-upload-token: $TOKEN" --data-binary @supabase/bundle.json \
//        https://<ref>.supabase.co/functions/v1/game/assets-upload
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const UPLOAD_TOKEN = process.env.ZFM_UPLOAD_TOKEN || 'zfm-upload-x7k2m9q4';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'supabase', 'functions', 'game');
fs.mkdirSync(path.join(outDir, 'game'), { recursive: true });
fs.mkdirSync(path.join(outDir, 'public', 'js'), { recursive: true });

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
};

const assets = {};
function addDir(dir, prefix) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) { addDir(p, prefix + f.name + '/'); continue; }
    assets[prefix + f.name] = {
      type: MIME[path.extname(f.name)] || 'application/octet-stream',
      gz: zlib.gzipSync(fs.readFileSync(p), { level: 9 }).toString('base64'),
    };
  }
}
addDir(path.join(root, 'public'), '');

fs.writeFileSync(path.join(root, 'supabase', 'bundle.json'), JSON.stringify(assets));

// sim core + shared constants, layout preserved so relative imports keep working
fs.copyFileSync(path.join(root, 'game', 'core.js'), path.join(outDir, 'game', 'core.js'));
fs.copyFileSync(path.join(root, 'public', 'js', 'shared.js'), path.join(outDir, 'public', 'js', 'shared.js'));

fs.writeFileSync(path.join(outDir, 'index.ts'), `// Zombies From Mars — Supabase Edge Function: static client + direct-mode WebSocket.
// Generated by scripts/build-edge.js; sim logic lives in game/core.js (shared with Node).
// Assets are stored in Supabase Storage (bucket "game-assets") and uploaded via
// POST /game/assets-upload with the x-upload-token header.
// @ts-ignore plain JS module
import { createHub } from './game/core.js';

const hub = createHub();
const UPLOAD_TOKEN = ${JSON.stringify(UPLOAD_TOKEN)};
const BUCKET = 'game-assets';
const SB_URL = Deno.env.get('SUPABASE_URL') ?? '';
const SB_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') ?? '';

type Manifest = Record<string, { type: string; gz: string }>;
let manifest: Manifest | null = null;
const cache = new Map<string, Uint8Array>();

async function loadManifest(): Promise<Manifest> {
  if (manifest) return manifest;
  const r = await fetch(\`\${SB_URL}/storage/v1/object/\${BUCKET}/bundle.json\`, {
    headers: { Authorization: \`Bearer \${SB_KEY}\` },
  });
  if (!r.ok) throw new Error('asset bundle not uploaded yet (' + r.status + ')');
  manifest = await r.json();
  return manifest!;
}

async function assetBody(key: string, man: Manifest): Promise<Uint8Array> {
  const hit = cache.get(key);
  if (hit) return hit;
  const gz = Uint8Array.from(atob(man[key].gz), (c) => c.charCodeAt(0));
  const ds = new DecompressionStream('gzip');
  const out = new Uint8Array(await new Response(new Blob([gz]).stream().pipeThrough(ds)).arrayBuffer());
  cache.set(key, out);
  return out;
}

Deno.serve(async (req: Request) => {
  const url = new URL(req.url);
  const m = url.pathname.match(/\\/game(\\/.*)?$/);
  let sub = (m && m[1]) || '';

  if (sub === '/ws') {
    if (req.headers.get('upgrade')?.toLowerCase() !== 'websocket') {
      return new Response('expected websocket', { status: 426 });
    }
    const { socket, response } = Deno.upgradeWebSocket(req);
    const client = hub.connect({ send: (s: string) => { try { socket.send(s); } catch (_) {} } });
    socket.onmessage = (ev) => client.onMessage(String(ev.data));
    socket.onclose = () => client.onClose();
    socket.onerror = () => client.onClose();
    return response;
  }

  if (sub === '/assets-upload' && req.method === 'POST') {
    if (req.headers.get('x-upload-token') !== UPLOAD_TOKEN) return new Response('forbidden', { status: 403 });
    const body = await req.text();
    try { JSON.parse(body); } catch (_) { return new Response('not json', { status: 400 }); }
    await fetch(\`\${SB_URL}/storage/v1/bucket\`, {
      method: 'POST',
      headers: { Authorization: \`Bearer \${SB_KEY}\`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ id: BUCKET, name: BUCKET, public: false }),
    }).catch(() => {});
    const up = await fetch(\`\${SB_URL}/storage/v1/object/\${BUCKET}/bundle.json\`, {
      method: 'POST',
      headers: { Authorization: \`Bearer \${SB_KEY}\`, 'Content-Type': 'application/json', 'x-upsert': 'true' },
      body,
    });
    manifest = null;
    cache.clear();
    return new Response('upload status: ' + up.status + ' ' + (await up.text()));
  }

  if (sub === '') {
    // trailing slash so relative asset URLs resolve under /game/
    return Response.redirect(url.origin + url.pathname + '/', 301);
  }
  if (sub === '/') sub = '/index.html';
  if (sub === '/healthz') return new Response('ok');

  try {
    const man = await loadManifest();
    const key = sub.replace(/^\\//, '');
    if (!man[key]) return new Response('not found', { status: 404 });
    const body = await assetBody(key, man);
    return new Response(body, {
      headers: { 'Content-Type': man[key].type, 'Cache-Control': 'public, max-age=300' },
    });
  } catch (e) {
    return new Response('assets unavailable: ' + (e as Error).message, { status: 503 });
  }
});
`);

const total = Object.values(assets).reduce((s, a) => s + a.gz.length, 0);
console.log(`bundle.json: ${Object.keys(assets).length} assets, ${(total / 1024 / 1024).toFixed(2)} MB (vendored three.js included)`);
